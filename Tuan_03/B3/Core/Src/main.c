/* --- HÀM CHÍNH --- */
int main(void)
{
  HAL_Init();
  SystemClock_Config();

  // THỨ TỰ BẮT BUỘC: Cấu hình DMA phải nằm TRƯỚC UART
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_USART1_UART_Init();

  while (1)
  {
    // Logic đếm khi có sự kiện bấm nút
    if (btn_flag == 1) {
        btn_count++;
        
        // Điền lại MSSV và số Nhóm của bạn vào chuỗi này
        uint16_t len = sprintf(uart_buf, "D23N03-Nhom6:BTN:%d\r\n", btn_count);
        
        // Bắn dữ liệu qua UART bằng DMA
        HAL_UART_Transmit_DMA(&huart1, (uint8_t*)uart_buf, len);
        
        btn_flag = 0;     // Xóa cờ ngắt
        HAL_Delay(250);   // Trễ 250ms để chống dội phím (debounce)
    }
  }
}

