// 5. Hàm vẽ ảnh bitmap (Đã tích hợp bộ dịch định dạng MONO_HMSB)
void SSD1306_DrawBitmap(const unsigned char* bitmap) {
    // Tạo một bộ đệm ảo 1024 byte trong RAM (Vi điều khiển của bạn có 20KB RAM nên rất thoải mái)
    uint8_t buffer[1024] = {0}; 

    // Chuyển đổi dữ liệu từ ảnh ngang (Horizontal) sang cấu trúc trang dọc (Vertical Page) của OLED
    for (int y = 0; y < 64; y++) {
        for (int x = 0; x < 128; x++) {
            // Xác định vị trí pixel trong mảng gốc của web (đọc theo hàng ngang)
            int byte_idx = (y * 128 + x) / 8;
            int bit_idx = 7 - (x % 8); // Chế độ HMSB (Bit quan trọng nhất nằm bên trái)
            
            // Nếu pixel tại vị trí này sáng (bit = 1)
            if (bitmap[byte_idx] & (1 << bit_idx)) {
                // Ánh xạ nó sang bộ đệm ảo của OLED (đọc theo cột dọc)
                int oled_byte = (y / 8) * 128 + x;
                int oled_bit = y % 8;
                buffer[oled_byte] |= (1 << oled_bit);
            }
        }
    }

    // Reset lại con trỏ màn hình OLED
    SSD1306_WriteCommand(0x21); 
    SSD1306_WriteCommand(0);    
    SSD1306_WriteCommand(127);  
    SSD1306_WriteCommand(0x22); 
    SSD1306_WriteCommand(0);    
    SSD1306_WriteCommand(7);    

    // Đổ toàn bộ bộ đệm ảo đã được dịch chuẩn xác ra màn hình
    for(int i = 0; i < 1024; i++) {
        SSD1306_WriteData(buffer[i]);
    }
}
