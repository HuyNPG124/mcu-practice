#include "i2c.h"

#define SSD1306_ADDR 0x78
// Hàm memset tự viết dùng cho bare-metal
void *memset(void *dst, int c, unsigned int n) {
    uint8_t *p = (uint8_t *)dst;
    while (n--) {
        *p++ = (uint8_t)c;
    }
    return dst;
}
// 1. Hàm gửi Lệnh (Command)
void SSD1306_WriteCommand(uint8_t cmd) {
    I2C_Start();
    I2C_SendAddr(SSD1306_ADDR, 0); 
    I2C_WriteData(0x00);           
    I2C_WriteData(cmd);            
    I2C_Stop();
}

// 2. Hàm gửi Dữ liệu (Data)
void SSD1306_WriteData(uint8_t data) {
    I2C_Start();
    I2C_SendAddr(SSD1306_ADDR, 0); 
    I2C_WriteData(0x40);           
    I2C_WriteData(data);           
    I2C_Stop();
}

// 3. Hàm khởi tạo màn hình (Bạn đã vô tình xóa mất hàm này)
void SSD1306_Init(void) {
    SSD1306_WriteCommand(0xC8); // Lật chiều dọc (COM Output Scan Direction)
    SSD1306_WriteCommand(0xA1); // Lật chiều ngang (Segment Re-map)
    SSD1306_WriteCommand(0xAE); // Tắt màn hình
    SSD1306_WriteCommand(0x20); // Chế độ bộ nhớ
    SSD1306_WriteCommand(0x00); // Horizontal Addressing
    SSD1306_WriteCommand(0x21); // Dải cột
    SSD1306_WriteCommand(0);    
    SSD1306_WriteCommand(127);  
    SSD1306_WriteCommand(0x22); // Dải trang
    SSD1306_WriteCommand(0);    
    SSD1306_WriteCommand(7);    
    SSD1306_WriteCommand(0x8D); // Charge Pump
    SSD1306_WriteCommand(0x14); 
    SSD1306_WriteCommand(0xAF); // Bật màn hình
}

